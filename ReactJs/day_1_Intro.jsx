// Features of React -
    // Virtual DOM - Faster than real DOM
    // XSS Protection - Cross site Scripting security
    // One way Binding - Parent -> child (props)
    // SPA (Single Page Application) -> Faster performance
    // JSX - HTMl -> JS in same file


// Tools and Libraries -
    // Testing - Jest
    // Routing - React Router
    // Mobile Apps - React Native
    // State Management - Redux / Mobx
    // Babel - Transpiler (convert JSX -> plain JS for browser)


// Disadvantages -
    // Virtual DOM needs more memory
    // More DOM manipulations
    // Only UI -> can't control full application flow
    // Needs 3rd party libraries for routing , state management

